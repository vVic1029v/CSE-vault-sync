#!/usr/bin/env python3
"""Shared helpers for the vault generator scripts.

Used by brightspace-pipeline (bsvault/*), timetable-mirror (mirror.py,
courses.py) via ``sys.path`` (see "Importing" below). Conventions:

- Every generated file: frontmatter at byte 0, then a banner line, then
  the generated body wrapped in AUTO_START / AUTO_END markers.
- THE MARKERS ARE ABSOLUTE (except Brightspace output, see below): on
  regeneration, tools replace ONLY the lines between the markers. Every
  byte outside them — headers, prose, user sections — is preserved
  verbatim. You own everything outside the markers.
- Frontmatter is preserved verbatim for existing files (so tree
  reparenting and manual tweaks survive); new files get template
  frontmatter. Tools may surgically maintain single derived lines
  (e.g. an `annotated:` flag) and must document it.
- Brightspace output is the exception: pure clone with no user-owned
  regions, wiped and rebuilt wholesale. Its markers label the generated
  body but nothing outside them can exist there by design.
- Frontmatter `sanitize` is DELIBERATELY NOT unified here: the Brightspace
  scraper replaces unsafe chars with `-` while the timetable mirror deletes
  them, and unifying would rename every generated file. Leave those local.

Importing (stdlib only, no install step):

    import sys
    from pathlib import Path
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent
                           / "vaultlib"))
    from autolib import AUTO_START, AUTO_END, banner, ...
"""

import os
import re
import stat

AUTO_START = "<!-- AUTO:START -->"
AUTO_END = "<!-- AUTO:END -->"

FULL_TAG = "autogenerated"
PARTIAL_TAG = "autogenerated/partial"


def tags_line(base, partial=False):
    """YAML tags line: base tags plus the autogenerated marker.

    Fully generated files get `autogenerated`; files mixing generated
    content with user-owned writable sections get `autogenerated/partial`.
    """
    return f"tags: [{', '.join([*base, PARTIAL_TAG if partial else FULL_TAG])}]"


def banner(tool, extra="do not edit, safe to re-run"):
    """File banner line (keeps the 'auto-generated' phrase health checks grep)."""
    return f"<!-- auto-generated by {tool} : {extra} -->\n"


def read_section(text, heading="## Notes"):
    """Last `heading` section body ('' when absent/empty).

    Runs to the next top-level (`# `) heading or EOF, so `##` subheadings
    inside user content are kept. Last match wins: user content always
    accrues at the end.
    """
    sections = re.findall(rf"^{re.escape(heading)}\s*\n(.*?)(?=^# |\Z)",
                          text, re.M | re.S)
    return sections[-1].strip() if sections else ""


def split_markers(text):
    """Split marked text into (head, auto, tail).

    head = everything through the blank line before START (frontmatter,
    banner, static headers); auto = lines between the markers
    (regenerated); tail = everything after the END line (user-owned).
    Returns (text, "", "") when the marker pair is absent.
    Recompose with: head + AUTO_START + "\\n" + new_auto
    + AUTO_END + "\\n" + tail.
    """
    start = text.find(AUTO_START)
    if start < 0:
        return text, "", ""
    end = text.find(AUTO_END, start)
    if end < 0:
        return text, "", ""
    head_end = text.rfind("\n", 0, start) + 1
    auto_start = text.find("\n", start) + 1
    auto_end = text.rfind("\n", 0, end)
    tail_nl = text.find("\n", end + len(AUTO_END))
    tail_start = len(text) if tail_nl < 0 else tail_nl + 1
    return text[:head_end], text[auto_start:auto_end], text[tail_start:]


def yq(value):
    """YAML double-quoted scalar."""
    return '"' + str(value).replace("\\", "\\\\").replace('"', "'") + '"'


def make_readonly(root):
    """chmod -R a-w (works on files too, for single-note locks)."""
    from pathlib import Path
    root = Path(root)
    if not root.exists():
        return
    members = [root] if root.is_file() else [root, *root.rglob("*")]
    for p in members:
        try:
            mode = os.stat(p).st_mode
            os.chmod(p, mode & ~(stat.S_IWUSR | stat.S_IWGRP | stat.S_IWOTH))
        except OSError:
            pass


def make_writable(root):
    """Clear read-only bits (works on files too)."""
    from pathlib import Path
    root = Path(root)
    if not root.exists():
        return
    members = [root] if root.is_file() else [root, *root.rglob("*")]
    for p in members:
        try:
            mode = os.stat(p).st_mode
            extra = stat.S_IXUSR if stat.S_ISDIR(mode) else 0
            os.chmod(p, mode | stat.S_IWUSR | extra)
        except OSError:
            pass
