#!/usr/bin/env python3
"""Vault-side course hubs: one note per Brightspace course in Courses/.

Each hub has an AUTO block (course meta, Brightspace link, upcoming-classes
Dataview table) wrapped in markers, plus a free user space (`## Notes`).
Regeneration rewrites ONLY the marked block; everything else is preserved
(keyed by filename). Hubs for vanished courses are pruned only when their
user space is empty. Each hub also gets a read-only Notebook child listing
every annotated class instance (Dataview embeds, chronological).

Usage:
  python3 courses.py [--vault ~/Documents/OBSIDIAN/holanda]
"""

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "vaultlib"))
from autolib import (AUTO_END, AUTO_START, banner, make_readonly,
                     make_writable, read_section, split_markers, tags_line)

HUB_BANNER = banner("courses-hub",
                    "user content outside markers is preserved")

HUB_PARENT = "! Course Notes"


def parent_auto():
    """Regenerated region: all upcoming imported classes (Timetable only)."""
    return [
        "## Upcoming classes",
        "",
        "> [!note]- 📚 Imported classes",
        "> Live Timetable mirror — hand-made `Sessions/` blocks excluded.",
        "",
        "```dataview",
        "TABLE WITHOUT ID dateformat(date, \"dd-MM\") "
        "+ \" \" + startTime AS When, link(file.link, title) AS Class, "
        "join(course_notes, \" · \") AS Course, room AS Room, "
        "lecture AS Notes",
        "FROM \"Timetable\"",
        "WHERE date >= date(today)",
        "SORT date ASC, startTime ASC",
        "LIMIT 30",
        "```",
    ]


def ensure_hub_parent_note(courses):
    """Create/upgrade the VirtFolder grouping MOC; regen only its AUTO block.

    Migrates the legacy `Course Notes.md` name once. Afterwards the static
    head (title + any user prose) is preserved verbatim and only the marked
    block regenerates — hence the partial tag.
    """
    vault = courses.parent
    old = vault / "Course Notes.md"
    path = vault / f"{HUB_PARENT}.md"
    if old.exists() and not path.exists():
        old.rename(path)
        print(f"  renamed Course Notes.md -> {HUB_PARENT}.md")
    auto = parent_auto()
    if path.exists():
        text = path.read_text(encoding="utf-8")
        if AUTO_START in text and AUTO_END in text:
            head, _, tail = split_markers(text)
            head_body = head.split("---", 2)[2] if head.startswith("---") \
                else head
            raw = (head_body + "\n" + tail).split("\n")
        else:
            body = text.split("---", 2)[2] if text.startswith("---") else text
            raw = body.split("\n")
        static = [ln for ln in raw
                  if ln.strip() and "auto-generated by" not in ln]
        static = [f"# {HUB_PARENT}" if ln.strip() == "# Course Notes"
                  else ln for ln in static]
        if not any(ln.startswith("# ") for ln in static):
            static = [f"# {HUB_PARENT}", ""] + static
        if not any("Grouping note" in ln for ln in static):
            static += ["", "Grouping note for the per-course hubs below — "
                       "nothing else lives here."]
    else:
        static = [f"# {HUB_PARENT}", "",
                  "Grouping note for the per-course hubs below — "
                  "nothing else lives here."]
    fm = ["---", f"title: {HUB_PARENT}",
          tags_line(["course-index", "moc"], partial=True), "Folders:",
          '  - "[[! Index]]"', "---"]
    text = "\n".join(fm + [HUB_BANNER.strip(), "", *static, "",
                           AUTO_START, *auto, AUTO_END]).rstrip() + "\n"
    path.write_text(text, encoding="utf-8")
    print(f"  updated {HUB_PARENT}.md")


def hub_static(title):
    """User-owned static region: title only (kept verbatim)."""
    return [f"# {title}", ""]


def hub_auto(dirname, code, n_classes, next_class):
    """Regenerated region: section header + meta callout + classes query."""
    return [
        "## Upcoming classes",
        "",
        "> [!note]- 📚 Course material",
        f"> - **Code:** {code}",
        f"> - Brightspace: [[Brightspace/{dirname}/{dirname}]] (read-only)",
        f"> - Notebook: [[Courses/{dirname} Notebook|📓 {dirname} Notebook]]",
        f"> - Timetable: {n_classes} upcoming classes"
        + (f", next {next_class}" if next_class else ""),
        "",
        "```dataview",
        "TABLE WITHOUT ID dateformat(date, \"dd-MM\") "
        "+ \" \" + startTime AS When, link(file.link, title) AS Class, "
        "join(course_notes, \" · \") AS Course, room AS Room, "
        "lecture AS Notes",
        "FROM \"Timetable\"",
        f"WHERE contains(codes, \"{code}\") AND date >= date(today)",
        "SORT date ASC, startTime ASC",
        "LIMIT 10",
        "```",
    ]


def hub_text(dirname, code, n_classes, next_class, notes):
    """Full hub note for NEW hubs: frontmatter + static + AUTO + user seed."""
    fm = ["---", f"title: {dirname}", f"code: {code}",
          tags_line(["course"], partial=True), "Folders:",
          f"  - \"[[{HUB_PARENT}]]\"", "---"]
    body = [HUB_BANNER.strip(), "",
            *hub_static(dirname),
            AUTO_START, *hub_auto(dirname, code, n_classes, next_class),
            AUTO_END, "",
            "## Notes", ""]
    if notes:
        body += [notes, ""]
    return "\n".join(fm + body).rstrip() + "\n"


def timetable_stats(timetable_dir, code):
    """(upcoming count, next date) for exact code matches in Timetable/."""
    import yaml
    n, nxt = 0, None
    if not timetable_dir.is_dir():
        return 0, None
    today = __import__("datetime").date.today().isoformat()
    for p in timetable_dir.glob("*.md"):
        try:
            fm = yaml.safe_load(p.read_text(encoding="utf-8").split("---", 2)[1])
        except Exception:
            continue
        if not isinstance(fm, dict):
            continue
        parts = [c.strip() for c in str(fm.get("course", "")).split("/")]
        if code not in parts:
            continue
        day = str(fm.get("date", ""))
        if day >= today:
            n += 1
            if nxt is None or day < nxt:
                nxt = day
    return n, nxt


def notebook_text(dirname, code):
    """Live notebook: linked headers + rendered Notes bodies, chronological.

    DataviewJS reads class-note bodies on every render, so typing appears
    instantly with no re-sync. Looks like hand-written ![[file]] sections.
    """
    fm = ["---", f"title: {dirname} Notebook", f"code: {code}",
          tags_line(["course-notebook"]), "view-mode-lock: reading", "Folders:",
          f"  - \"[[Courses/{dirname}]]\"", "---"]
    body = [HUB_BANNER.strip(), "",
            AUTO_START,
            f"# {dirname} — Notebook", "",
            "> [!info]- 📓 Annotated class notes, oldest first",
            "> Live view — updates as you type in class notes. Write there; "
            "this note is read-only.",
            "",
            "```dataviewjs",
            "const CODE = " + json.dumps(code) + ";",
            "const pages = dv.pages('\"Timetable\"')",
            "  .where(p => p.codes && p.codes.includes(CODE))",
            "  .sort(p => p.file.name, 'asc');",
            "let shown = 0;",
            "for (const p of pages) {",
            "  const text = await dv.io.load(p.file.path);",
            "  const lines = text.split('\\n');",
            "  let start = -1;",
            "  for (let i = lines.length - 1; i >= 0; i--) {",
            "    if (/^## Notes\\s*$/.test(lines[i])) { start = i; break; }",
            "  }",
            "  let content = '';",
            "  if (start >= 0) {",
            "    const rest = lines.slice(start + 1);",
            "    let end = rest.findIndex(l => /^# /.test(l));",
            "    content = (end < 0 ? rest : rest.slice(0, end))",
            "      .join('\\n').trim();",
            "  }",
            "  if (!content) continue;",
            "  shown++;",
            "  const label = (p.date && p.date.toISODate ? p.date.toISODate() "
            ": p.date) + ' ' + (p.startTime || '') + ' — ' + "
            "(p.title || p.file.name);",
            "  dv.header(2, '[[' + p.file.path + '|' "
            "+ label.replace(/\\|/g, '-') + ']]');",
            "  dv.paragraph(content);",
            "}",
            "if (!shown) dv.paragraph('_No annotated class notes yet — "
            "write under `## Notes` in any class note._');",
            "```",
            AUTO_END,
            ""]
    return "\n".join(fm + body).rstrip() + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--vault", default=str(Path.home() / "Documents/OBSIDIAN/holanda"))
    args = ap.parse_args(argv)
    vault = Path(args.vault).expanduser()
    bs, courses = vault / "Brightspace", vault / "Courses"
    courses.mkdir(parents=True, exist_ok=True)
    ensure_hub_parent_note(courses)
    live = sorted(d.name for d in bs.iterdir()
                  if d.is_dir()) if bs.is_dir() else []
    if not live:
        print("COURSES: no Brightspace courses found, nothing to do")
        return
    for dirname in live:
        if not (bs / dirname).is_dir():
            continue
        code = dirname.split(" - ", 1)[0]
        n, nxt = timetable_stats(vault / "Timetable", code)
        path = courses / f"{dirname}.md"
        auto = hub_auto(dirname, code, n, nxt)
        if path.exists():
            # Surgical: keep head (incl. frontmatter) + tail verbatim,
            # regenerate only between the markers. Reparent legacy hubs
            # (! Index, Course Notes) under ! Course Notes; user-moved
            # hubs keep their parent.
            text = path.read_text(encoding="utf-8")
            head, _, tail = split_markers(text)
            head = head.replace('- "[[! Index]]"',
                                f'- "[[{HUB_PARENT}]]"')
            head = head.replace('- "[[Course Notes]]"',
                                f'- "[[{HUB_PARENT}]]"')
            text = head + AUTO_START + "\n" + "\n".join(auto) + \
                "\n" + AUTO_END + "\n" + tail
            print(f"  updated Courses/{dirname}.md")
        else:
            text = hub_text(dirname, code, n, nxt, "")
            print(f"  wrote Courses/{dirname}.md")
        path.write_text(text.rstrip() + "\n", encoding="utf-8")
        nb = courses / f"{dirname} Notebook.md"
        if nb.exists():
            make_writable(nb)
        nb.write_text(notebook_text(dirname, code), encoding="utf-8")
        make_readonly(nb)
    # prune hubs whose course vanished AND whose user space is empty;
    # orphan notebooks (pure views) always prune
    for path in sorted(courses.glob("*.md")):
        is_nb = path.stem.endswith(" Notebook")
        base = path.stem[:-len(" Notebook")] if is_nb else path.stem
        if base in live:
            continue
        if is_nb:
            path.unlink()
            print(f"  pruned orphan notebook: Courses/{path.name}")
            continue
        text = path.read_text(encoding="utf-8")
        notes = read_section(text.split("---", 2)[2] if text.startswith("---") else text)
        if notes:
            print(f"  kept stale hub (has notes): Courses/{path.name}")
        else:
            path.unlink()
            print(f"  pruned stale hub: Courses/{path.name}")
    print(f"COURSES: {len(live)} hubs")


if __name__ == "__main__":
    main()
