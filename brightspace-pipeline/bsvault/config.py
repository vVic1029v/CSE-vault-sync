"""Shared constants and filesystem locations.

The old single-file script mutated module globals (VAULT/CACHE/RAW) via
configure_output(). Instead, build_paths() returns one Paths object that is
passed explicitly through sync -> vault. Nothing here is secret.
"""

from dataclasses import dataclass
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent
                       / "vaultlib"))
try:
    from autolib import AUTO_END, AUTO_START, banner
except ImportError:  # vaultlib missing: generated output loses markers
    AUTO_START, AUTO_END = "<!-- AUTO:START -->", "<!-- AUTO:END -->"

    def banner(tool, extra="do not edit, safe to re-run"):
        return f"<!-- auto-generated by {tool} : {extra} -->\n"

BASE = "https://brightspace.tudelft.nl"
LP_VER = "1.43"
LE_VER = "1.75"
UA = ("Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 "
      "(KHTML, like Gecko) Chrome/126.0 Safari/537.36")

HOME = Path.home()
SCRIPT_DIR = Path(__file__).resolve().parent.parent
STATE = SCRIPT_DIR / "_state"          # session/cookies live with the script

KEEP_EXTS = {".pdf", ".pptx", ".ppt", ".xlsx", ".xls", ".docx", ".txt", ".md",
             ".zip", ".gz", ".tgz", ".s", ".py", ".vim", ".c", ".h", ".java",
             ".jpg", ".jpeg", ".png", ".gif", ".svg", ".mp4", ".csv"}
IMAGE_EXTS = {".jpg", ".jpeg", ".png", ".gif", ".svg"}
AUTO_TAG = banner("main.py")


@dataclass(frozen=True)
class Paths:
    """Every directory the pipeline reads or writes. vault is the ONLY output."""
    vault: Path      # the Obsidian vault (-o)
    cache: Path      # sync cache (raw API clone + manifest)
    raw: Path        # RAW clone inside the cache
    state: Path      # session/cookies/screenshots, lives with the script
    cookies: Path    # cookie jar path


def build_paths(vault_dir, cache_dir=None, cookies_path=None):
    """Compose the Paths for one run from CLI options."""
    vault = Path(vault_dir).expanduser().resolve()
    cache = Path(cache_dir).expanduser().resolve() if cache_dir else STATE / "cache"
    cookies = Path(cookies_path).expanduser() if cookies_path \
        else STATE / "cookies.json"
    return Paths(vault=vault, cache=cache, raw=cache / "raw",
                 state=STATE, cookies=cookies)
